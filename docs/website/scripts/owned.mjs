import { constants } from 'node:fs';
import { link, mkdtemp, open, rmdir, unlink, writeFile } from 'node:fs/promises';
import path from 'node:path';

export const marker = '<!-- Generated by docs/website/scripts/generate.mjs; do not edit. -->';
export function staleOwned(previous, current) {
  for (const name of [...previous, ...current]) {
    if (!/^[a-z0-9-]+(?:\/[a-z0-9-]+)*\.md$/.test(name)) throw new Error(`unsafe generated path: ${name}`);
  }
  const keep = new Set(current);
  return previous.filter(name => !keep.has(name));
}

export async function discoverOwned(root, prefix = '') {
  const { readdir, readFile } = await import('node:fs/promises');
  const path = await import('node:path');
  let entries;
  try { entries = await readdir(path.join(root, prefix), { withFileTypes: true }); }
  catch (error) { if (error.code === 'ENOENT') return []; throw error; }
  const owned = [];
  for (const entry of entries) {
    const name = path.posix.join(prefix, entry.name);
    if (entry.isDirectory()) owned.push(...await discoverOwned(root, name));
    else if (entry.isFile() && name.endsWith('.md')) {
      const text = await readFile(path.join(root, name), 'utf8');
      if (text.endsWith(`${marker}\n`)) owned.push(name);
    }
  }
  return owned.sort();
}

export async function removeStaleOwned(root, previous, current) {
  const { readFile, unlink } = await import('node:fs/promises');
  const path = await import('node:path');
  const discovered = await discoverOwned(root);
  for (const name of staleOwned([...new Set([...previous, ...discovered])], current)) {
    const target = path.join(root, name);
    let text;
    try { text = await readFile(target, 'utf8'); }
    catch (error) { if (error.code === 'ENOENT') continue; throw error; }
    if (!text.endsWith(`${marker}\n`)) throw new Error(`Refusing to remove unmarked file ${target}`);
    await unlink(target);
  }
}

export async function inspectOwned(target, openFile = undefined) {
  const handle = await (openFile ?? open)(target, constants.O_RDONLY | constants.O_NOFOLLOW | constants.O_NONBLOCK);
  try {
    const stat = await handle.stat();
    return stat.isFile() && (await handle.readFile('utf8')).endsWith(`${marker}\n`);
  } finally {
    await handle.close();
  }
}

export async function preflight(root, pages) {
  const { lstat } = await import('node:fs/promises');
  const path = await import('node:path');
  const sources = new Set();
  const routes = new Set();
  for (const [source, slug] of pages) {
    if (typeof source !== 'string' || !/^[a-z0-9-]+(?:\/[a-z0-9-]+)*\.md$/.test(source) ||
        typeof slug !== 'string' || !/^[a-z0-9-]+(?:\/[a-z0-9-]+)*$/.test(slug)) throw new Error('unsafe source or route');
    if (sources.has(source)) throw new Error(`duplicate source: ${source}`);
    sources.add(source);
    if (slug === 'index') throw new Error('reserved homepage route');
    const route = slug.replace(/\/index$/, '');
    if (routes.has(route)) throw new Error(`duplicate route: ${route}`);
    routes.add(route);
  }
  try {
    const rootStat = await lstat(root);
    if (rootStat.isSymbolicLink() || !rootStat.isDirectory()) throw new Error(`Unsafe output root: ${root}`);
  } catch (error) { if (error.code !== 'ENOENT') throw error; }
  for (const [, slug] of pages) {
    const segments = `${slug}.md`.split('/');
    let target = root;
    for (const [index, segment] of segments.entries()) {
      target = path.join(target, segment);
      if (index === segments.length - 1) {
        let owned;
        try { owned = await inspectOwned(target); }
        catch (error) {
          if (error.code === 'ENOENT') break;
          if (error.code === 'ELOOP') throw new Error(`Refusing symlink: ${target}`);
          throw error;
        }
        if (!owned) throw new Error(`Refusing unmarked file: ${target}`);
      } else {
        let stat;
        try { stat = await lstat(target); }
        catch (error) { if (error.code === 'ENOENT') break; throw error; }
        if (stat.isSymbolicLink()) throw new Error(`Refusing symlink: ${target}`);
        if (!stat.isDirectory()) throw new Error(`Not a directory: ${target}`);
      }
    }
  }
}

// Generation assumes one writer and a trusted, writable parent with hard-link support.
// The handle keeps the checked leaf bound during replacement.
export async function writeOwned(target, content) {
  const flags = constants.O_RDWR | constants.O_NOFOLLOW | constants.O_NONBLOCK;
  // A hard link installs the ownership marker atomically without replacing an existing path.
  const staging = await mkdtemp(path.join(path.dirname(target), '.gvy-stage-'));
  const seed = path.join(staging, 'seed');
  try {
    await writeFile(seed, `${marker}\n`, { flag: 'wx' });
    try { await link(seed, target); }
    catch (error) { if (error.code !== 'EEXIST') throw error; }
  } finally {
    try { await unlink(seed); } catch (error) { if (error.code !== 'ENOENT') throw error; }
    await rmdir(staging);
  }
  const handle = await open(target, flags);
  try {
    const stat = await handle.stat();
    if (!stat.isFile() || !(await handle.readFile('utf8')).endsWith(`${marker}\n`)) {
      throw new Error(`Refusing unmarked file: ${target}`);
    }
    await handle.truncate(0);
    const bytes = Buffer.from(content);
    let offset = 0;
    while (offset < bytes.length) {
      const { bytesWritten } = await handle.write(bytes, offset, bytes.length - offset, offset);
      if (!bytesWritten) throw new Error(`Failed to write ${target}`);
      offset += bytesWritten;
    }
  } finally {
    await handle.close();
  }
}
